test('guest expiry deletes only a confirmed bot-created overwrite; an ambiguous write is flagged for manual review', async () => {
  const f = await adminFixture();
  const team = await f.team('events', { flags: elevated });
  const room = await privateRoom(f, team, 'guest');
  await f.room('guest', room);
  await f.enable();
  const grant = (id) => f.admin.room.guest(f.make(), { user: user(id), minutes: 1 });
  await grant(MEMBER_ID);
  const write = f.api.putOverwrite.bind(f.api);
  f.api.putOverwrite = async (...args) => { await write(...args); throw new DiscordApiError(502); };
  await assert.rejects(grant(STRANGER), { status: 502 });
  f.clock.at += MIN;
  await f.restart().tick();
  assert.equal(ownOverwrite(f, room.id, MEMBER_ID), undefined);
  assert.deepEqual(ownOverwrite(f, room.id, STRANGER), own(STRANGER, P.ViewChannel));
  const [lease] = Object.values((await snap(f)).leases);
  assert.equal(lease.subject, STRANGER);
  assert.equal(lease.failed, true);
  assert.deepEqual(operation(f, 'deleteOverwrite').map(({ userId }) => userId), [MEMBER_ID]);
});
