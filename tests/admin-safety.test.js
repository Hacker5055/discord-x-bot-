import assert from 'node:assert/strict';
import test from 'node:test';
import { ChannelType as C, PermissionFlagsBits as P } from 'discord.js';
import { adminOf } from '../src/admin/core.js';
import { CATEGORY_NAME, ROLES } from '../src/lib/catalog.js';
import { DiscordApiError } from '../src/lib/errors.js';
import { ANIME, REVIEWER, STRANGER, adminFixture, asText, group, own, user } from './fixtures/admin.js';
import { BOT_ROLE_ID, FAKE_API_SECRET, GUILD_ID, MEMBER_ID, MOD_ID } from './fixtures/discord.js';

const snap = async (f) => adminOf(await f.store.read());
const MIN = 60_000;
const elevated = P.ManageChannels | P.ManageRoles;
const ops = (f, by = MOD_ID) => f.make({ by, channel: f.staffRoom });
const ownOverwrite = (f, channelId, id) => f.api.channel(channelId).permission_overwrites.find((o) => o.id === id && o.type === 1);
const operation = (f, name) => f.api.writes.filter(({ operation }) => operation === name);

async function privateRoom(f, staff, name = 'restricted') {
  return f.chan(C.GuildText, name, { permission_overwrites: [group(GUILD_ID, 0n, P.ViewChannel), group(staff.id, P.ViewChannel), own(f.botId, P.ViewChannel)] });
}

test('access diagnoses actual overwrites and timeouts; layout capture/diff detects drift but never restores Discord', async () => {
  const f = await adminFixture();
  const staff = await f.team('ops', { flags: elevated });
  const room = await privateRoom(f, staff);
  await f.team('ops', { channel: room, withRole: staff });
  await f.enable();
  const before = f.api.writes.length;
  const scope = () => ops(f);
  const input = { channel: room, user: user(MEMBER_ID) };
  const diag = asText(await f.admin.diagnostics.access(scope(), input));
  assert.match(diag, /الرؤية: ممنوعة · الكتابة: ممنوعة/);
  assert.match(diag, /رولات لها سماح ومش عند العضو/);
  assert.match(diag, new RegExp(staff.id));
  await assert.rejects(f.admin.diagnostics.access(f.make({ by: MOD_ID }), input), { code: 'ADMIN_SCOPE' });
  await f.admin.diagnostics.capture(f.make());
  assert.match(asText(await f.admin.diagnostics.diff(f.make())), /0 اختلاف/);
  f.api.channel(room.id).permission_overwrites.push(own(MEMBER_ID, P.ViewChannel));
  f.api.members.get(MEMBER_ID).communication_disabled_until = new Date(f.now() + MIN).toISOString();
  f.api.roles.find((r) => r.id === staff.id).permissions = String(elevated | P.ManageMessages);
  f.api.channel(room.id).name = FAKE_API_SECRET;
  assert.match(asText(await f.admin.diagnostics.access(scope(), input)), /الرؤية: مسموحة · الكتابة: ممنوعة.*Timeout/);
  const diff = asText(await f.admin.diagnostics.diff(f.make()));
  assert.match(diff, /2 اختلاف/);
  assert.doesNotMatch(diff, new RegExp(FAKE_API_SECRET));
  assert.equal(f.api.writes.length, before);
});

test('a separate approver must still have live scope, confirm, and match the before state for a sensitive room change', async () => {
  const f = await adminFixture({ setup: true });
  const staff = await f.team('ops', { flags: elevated, users: [MOD_ID, REVIEWER] });
  const target = await privateRoom(f, staff);
  await f.team('ops', { channel: target, withRole: staff });
  await f.enable();
  const proposal = ops(f);
  const args = { channel: target, user: user(MEMBER_ID), visibility: 'allow' };
  const a = { id: proposal.id, confirm: true };
  await f.admin.room.propose(proposal, args);
  assert.equal(operation(f, 'putOverwrite').length, 0);
  assert.match(asText(await f.admin.room.pending(ops(f, REVIEWER))), /مش محدد → سماح صريح/);
  await assert.rejects(f.admin.room.approve(ops(f), a), { code: 'ADMIN_SCOPE' });
  await assert.rejects(f.admin.room.approve(ops(f, STRANGER), a), { code: 'ADMIN_SCOPE' });
  assert.match(asText(await f.admin.room.approve(ops(f, REVIEWER), { ...a, confirm: false })), /معاينة/);
  f.api.channel(target.id).permission_overwrites.push(own(MEMBER_ID, P.EmbedLinks));
  await assert.rejects(f.admin.room.approve(ops(f, REVIEWER), a), { code: 'ADMIN_STALE' });
  f.api.channel(target.id).permission_overwrites.pop();
  f.api.members.get(MOD_ID).roles = [];
  await assert.rejects(f.admin.room.approve(ops(f, REVIEWER), a), { code: 'ADMIN_SCOPE' });
  f.api.members.get(MOD_ID).roles = [staff.id];
  await f.admin.room.approve(ops(f, REVIEWER), a);
  assert.deepEqual(ownOverwrite(f, target.id, MEMBER_ID), own(MEMBER_ID, P.ViewChannel));
  assert.equal((await snap(f)).proposals[proposal.id].approvedBy, REVIEWER);
  await assert.rejects(f.admin.room.approve(ops(f, REVIEWER), a), { code: 'ADMIN_STALE' });
  assert.equal(operation(f, 'putOverwrite').length, 1);
  const second = ops(f);
  await f.admin.room.propose(second, { ...args, visibility: 'deny' });
  f.clock.at += 31 * MIN;
  await assert.rejects(f.admin.room.approve(ops(f, REVIEWER), { id: second.id, confirm: true }), { code: 'ADMIN_STALE' });
  const managed = f.api.channels.find((c) => c.name === CATEGORY_NAME);
  const extra = await f.chan(C.GuildText, 'also-protected', { parent_id: managed.id });
  await assert.rejects(f.admin.room.propose(f.make(), { ...args, channel: extra }), { code: 'ADMIN_PROTECTED_ROOM' });
});

test('slow mode is confirmed, restored across a restart, and not restored after a manual change even if changed back', async () => {
  const f = await adminFixture();
  const staff = await f.team('ops', { flags: P.ManageChannels });
  await f.team('ops', { withRole: staff, channel: f.publicRoom });
  await f.enable();
  const room = f.api.channel(f.publicRoom.id);
  room.rate_limit_per_user = 2;
  const args = { channel: room, seconds: 10, minutes: 1 };
  const by = () => ops(f);
  assert.match(asText(await f.admin.room.slow(by(), args)), /2 → 10/);
  assert.equal(room.rate_limit_per_user, 2);
  await f.admin.room.slow(by(), { ...args, confirm: true });
  assert.equal(room.rate_limit_per_user, 10);
  f.clock.at += MIN;
  await f.admin.config.enable(f.make(), { enabled: false });
  await f.restart().tick();
  assert.equal(room.rate_limit_per_user, 2);
  assert.equal(Object.keys((await snap(f)).leases).length, 0);
  await f.enable();
  await f.admin.room.slow(by(), { ...args, confirm: true });
  f.clock.at += 100;
  f.api.offsetSlowMode(room.id, 21, REVIEWER);
  f.clock.at += 100;
  f.api.offsetSlowMode(room.id, 10, REVIEWER);
  f.clock.at += MIN;
  await f.admin.tick();
  assert.equal(room.rate_limit_per_user, 10);
  assert.ok((await snap(f)).audit.some((r) => r.action === 'slow_ended' && r.outcome === 'changed_elsewhere'));
});

test('timed slow mode fails closed without an audit trail and a definitive Discord rejection does not leave an active lease', async () => {
  const f = await adminFixture();
  await f.enable();
  const room = f.api.channel(f.publicRoom.id);
  const args = { channel: room, seconds: 5, minutes: 1, confirm: true };
  const botRole = f.api.roles.find((r) => r.id === BOT_ROLE_ID);
  const original = botRole.permissions;
  botRole.permissions = String(BigInt(original) & ~P.ViewAuditLog);
  await assert.rejects(f.admin.room.slow(f.make(), args), { code: 'ADMIN_BOT_PERMISSION' });
  assert.equal(operation(f, 'updateChannel').length, 0);
  botRole.permissions = original;
  const update = f.api.updateChannel.bind(f.api);
  f.api.updateChannel = async () => { throw new DiscordApiError(403, 50013); };
  await assert.rejects(f.admin.room.slow(f.make(), args), { status: 403 });
  assert.equal(Object.keys((await snap(f)).leases).length, 0);
  f.api.updateChannel = update;
  const change = f.make();
  await f.admin.room.slow(change, args);
  f.api.channelAudits = [];
  for (let n = 0; n < 6; n++) { f.clock.at += 16 * MIN; await f.admin.tick(); }
  const [lease] = Object.values((await snap(f)).leases);
  assert.equal(lease.failed, true);
  assert.equal(room.rate_limit_per_user, 5);
  await f.admin.room.forget(f.make(), { id: change.id });
  assert.equal(Object.keys((await snap(f)).leases).length, 0);
  assert.equal(room.rate_limit_per_user, 5);
});

test('guest expiry touches only its exact recorded member overwrite and leaves roles and later manual edits untouched', async () => {
  const f = await adminFixture({ setup: true });
  const team = await f.team('events', { flags: elevated });
  const room = await privateRoom(f, team, 'guest');
  await f.team('events', { withRole: team, channel: room });
  await f.room('guest', room);
  await f.enable();
  const vip = f.api.roles.find(({ name }) => name === ROLES.vip_basic.name);
  f.api.members.get(MEMBER_ID).roles.push(vip.id);
  const previous = own(MEMBER_ID, P.EmbedLinks, P.SendMessages);
  f.api.channel(room.id).permission_overwrites.push(previous);
  const grant = (id) => f.admin.room.guest(ops(f), { user: user(id), minutes: 2 });
  await grant(MEMBER_ID);
  assert.deepEqual(ownOverwrite(f, room.id, MEMBER_ID), own(MEMBER_ID, P.ViewChannel | P.EmbedLinks, P.SendMessages));
  await grant(STRANGER);
  const manual = own(STRANGER, P.ViewChannel | P.SendMessages);
  Object.assign(ownOverwrite(f, room.id, STRANGER), manual);
  const bypass = await grant(MOD_ID);
  assert.match(asText(bypass), /الروم بالفعل/);
  f.clock.at += 2 * MIN;
  await f.restart().tick();
  assert.deepEqual(ownOverwrite(f, room.id, MEMBER_ID), previous);
  assert.deepEqual(ownOverwrite(f, room.id, STRANGER), manual);
  assert.deepEqual(f.api.members.get(MEMBER_ID).roles, [vip.id]);
  assert.equal(operation(f, 'revokeRole').length, 0);
  assert.equal(Object.keys((await snap(f)).leases).length, 0);
});

test('onboarding stays one mention-free card; stale settings and privileged or product-role interests never grant', async () => {
  const f = await adminFixture({ setup: true });
  await f.enable();
  await f.room('ticket_panel', f.staffRoom);
  const role = await f.role('Interest');
  const vip = f.api.roles.find(({ name }) => name === ROLES.vip_monarch.name);
  await assert.rejects(f.admin.config.interest(f.make(), { interest: 'news', role: vip }), { code: 'ADMIN_UNSAFE_ROLE' });
  await f.admin.config.interest(f.make(), { interest: 'news', role });
  await f.admin.guide.publish(f.make(), { rules: f.staffRoom });
  const panel = f.api.messages[0];
  const click = () => f.make({ by: MEMBER_ID, customId: 'bx:x:interest:news', messageId: panel.id });
  assert.match(asText(panel.data), /خريطة الرومات/);
  assert.match(asText(panel.data), new RegExp(f.staffRoom.id));
  assert.deepEqual(panel.data.allowed_mentions, { parse: [] });
  await f.admin.button(click());
  assert.deepEqual(f.api.members.get(MEMBER_ID).roles, [role.id]);
  await f.admin.button(click());
  assert.deepEqual(f.api.members.get(MEMBER_ID).roles, []);
  await f.admin.config.interest(f.make(), { interest: 'news', role });
  await assert.rejects(f.admin.button(click()), { code: 'ADMIN_STALE' });
  await f.admin.guide.publish(f.make(), { rules: f.staffRoom });
  assert.equal(f.api.messages.length, 1);
  f.api.roles.find((r) => r.id === role.id).permissions = String(P.ManageRoles);
  await assert.rejects(f.admin.button(click()), { code: 'ADMIN_UNSAFE_ROLE' });
  assert.equal(operation(f, 'grantRole').length, 1);
});

